_ADJ_SOFT3 = (("ий", "ьего", "ьему", "ий", "ьим", "ьем"), ("ья", "ьей", "ьей", "ью", "ьей", "ьей"),
              ("ье", "ьего", "ьему", "ье", "ьим", "ьем"), ("ьи", "ьих", "ьим", "ьи", "ьими", "ьих"))
_ADJ_K = (("ий", "ого", "ому", "ий", "им", "ом"), ("ая", "ой", "ой", "ую", "ой", "ой"),
          ("ое", "ого", "ому", "ое", "им", "ом"), ("ие", "их", "им", "ие", "ими", "их"))
GNUM = ("m", "f", "n", "pl")


def adjective(nom_m: str, case: str, gnum: str) -> str:
    """первый / второй / третий / кубический in any case, gender or the plural."""
    i, k = CASES.index(case), GNUM.index(gnum)
    if nom_m == "третий":
        return "трет" + _ADJ_SOFT3[k][i]
    if nom_m.endswith(("кий", "гий", "хий")):
        return nom_m[:-2] + _ADJ_K[k][i]
    stem = nom_m[:-2]
    if nom_m.endswith("ой") and gnum == "m" and case in ("nom", "acc"):
        return nom_m                                         # второй, сороковой: the stressed masculine ending
    return stem + _ADJ_HARD[k][i]


