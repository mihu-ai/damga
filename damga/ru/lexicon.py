# Nouns that are counted: (gender, singular forms by case, plural forms by case).
Noun = tuple[str, tuple[str, ...], tuple[str, ...]]


def _hard_m(stem: str, gen_pl: str | None = None) -> Noun:
    """доллар → доллара, доллару, долларом, долларе; долларов"""
    return ("m", (stem, stem + "а", stem + "у", stem, stem + "ом", stem + "е"),
            (stem + "ы", gen_pl or stem + "ов", stem + "ам", stem + "ы", stem + "ами", stem + "ах"))


def _fem_a(stem: str, gen_pl: str, soft_i: bool = False) -> Noun:
    """тонна → тонны …; минута → минуты …; копейка → копейки (soft_i: -и after к, г, х, ж, ш, ч, щ)"""
    y = "и" if soft_i else "ы"
    return ("f", (stem + "а", stem + y, stem + "е", stem + "у", stem + "ой", stem + "е"),
            (stem + y, gen_pl, stem + "ам", stem + y, stem + "ами", stem + "ах"))


